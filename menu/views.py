def menu(request):
    groups = []
    for category, entries in MENU_DATA.items():
        items = [
            {"name": name, "description": description, "price": price, "tag": tag, "category": category}
            for name, description, price, tag in entries
        ]
        groups.append({"name": category, "items": items, **CATEGORY_DETAILS[category]})

    return render(
        request,
        "menu/menu.html",
        {"groups": groups, "item_count": sum(len(group["items"]) for group in groups)},
    )


def menu_qr(request):
    target = request.build_absolute_uri("/")
    image = qrcode.make(target, border=2)
    output = BytesIO()
    image.save(output, format="PNG")
    response = HttpResponse(output.getvalue(), content_type="image/png")
    response["Content-Disposition"] = 'inline; filename="sare-kooche-menu-qr.png"'
    return response
