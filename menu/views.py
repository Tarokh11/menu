def menu(request):
    groups = []
    for category, entries in MENU_DATA.items():
        items = []
        for name, description, price, tag in entries:
            item = {
                "name": name,
                "description": description,
                "price": price,
                "tag": tag,
                "category": category,
            }
            items.append(item)
        groups.append({"name": category, "items": items})

    return render(
        request,
        "menu/menu.html",
        {"groups": groups, "item_count": sum(len(group["items"]) for group in groups)},
    )


def hero_demo(request):
    return render(
        request,
        "demos/hero_fresh.html",
        {"item_count": sum(len(entries) for entries in MENU_DATA.values())},
    )


def menu_qr(request):
    target = request.build_absolute_uri("/")
    image = qrcode.make(target, border=2)
    output = BytesIO()
    image.save(output, format="PNG")
    response = HttpResponse(output.getvalue(), content_type="image/png")
    response["Content-Disposition"] = 'inline; filename="vita-menu-qr.png"'
    return response
