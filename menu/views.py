CATEGORY_CODES = ["HOT COFFEE", "ICED COFFEE", "TEA & INFUSIONS", "HOUSE DRINKS", "BREAKFAST & BITES", "BAKERY"]


def menu(request):
    groups = []
    for (category, entries), code in zip(MENU_DATA.items(), CATEGORY_CODES):
        items = [
            {"name": name, "description": description, "price": price, "tag": tag}
            for name, description, price, tag in entries
        ]
        groups.append({"name": category, "items": items, "code": code})
    return render(request, "menu/menu.html", {
        "groups": groups, "item_count": sum(len(group["items"]) for group in groups),
    })


def menu_qr(request):
    image = qrcode.make(request.build_absolute_uri("/"), border=4)
    output = BytesIO()
    image.save(output, format="PNG")
    response = HttpResponse(output.getvalue(), content_type="image/png")
    response["Content-Disposition"] = 'inline; filename="aram-cafe-menu-qr.png"'
    return response
